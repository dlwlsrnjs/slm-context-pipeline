"""Aggregate every eval_results/*/summary.json into a single markdown table.

Output: icrl_math/ANALYSIS.md (overwritten on each run).

Picks the *most complete* GSM8K summary (the one with the most conditions) and
likewise for MATH500. Builds:
  1. A model card listing every LoRA + training config
  2. A GSM8K table — rows: conditions, cols: prompt variant
  3. A MATH500 table
  4. Key deltas: demo-only effect, curriculum vs no-curriculum, etc.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
EVAL_ROOT = HERE / "eval_results"


def load_summaries():
    out = {}
    for d in EVAL_ROOT.iterdir() if EVAL_ROOT.exists() else []:
        p = d / "summary.json"
        if p.exists():
            try:
                out[d.name] = json.load(open(p))
            except Exception as e:
                print(f"skip {p}: {e}")
    return out


def pick_widest(summaries, prefer_substr):
    """Pick the summary dict with the most conditions whose name contains the substring."""
    candidates = [(k, v) for k, v in summaries.items() if prefer_substr in k]
    if not candidates:
        return None, None
    candidates.sort(key=lambda kv: len(kv[1].get("results", {})), reverse=True)
    return candidates[0]


def to_table(results, conditions, prompts=("base", "demos")):
    lines = [f"| condition | {' | '.join(prompts)} |",
             f"|---|{'|'.join(['---']*len(prompts))}|"]
    for c in conditions:
        row = [c]
        for p in prompts:
            key = f"{c}__{p}" if c.startswith("phase_") else f"{c}_{p}"
            # baseline keys are baseline_base / baseline_demos
            if c == "baseline":
                key = f"baseline_{p}"
            v = results.get(key, {}).get("em")
            row.append(f"{v:.3f}" if v is not None else "—")
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def main():
    sums = load_summaries()
    name_gsm, gsm = pick_widest(sums, "cross")
    name_math, math = pick_widest(sums, "math500")

    out = ["# ICRL-Math: Final Results Snapshot",
           "",
           "_Auto-generated by `scripts/aggregate_results.py`._",
           ""]

    if gsm:
        out += [f"## GSM8K test (n={gsm.get('n','?')}, source: `{name_gsm}`)",
                ""]
        conds = ["baseline"] + sorted({k.split("__")[0] for k in gsm["results"] if k.startswith("phase_")})
        out += [to_table(gsm["results"], conds), ""]

        b_base = gsm["results"].get("baseline_base", {}).get("em")
        b_demos = gsm["results"].get("baseline_demos", {}).get("em")
        pb_base = gsm["results"].get("phase_b__base", {}).get("em")
        pc_base = gsm["results"].get("phase_c__base", {}).get("em")
        out += ["### Key deltas",
                ""]
        if b_base is not None and b_demos is not None:
            out.append(f"- **Demo-only effect**: {b_demos-b_base:+.3f}  (baseline_demos − baseline_base)")
        if b_base is not None and pb_base is not None:
            out.append(f"- **Phase B 0-shot transfer**: {pb_base-b_base:+.3f}  (phase_b__base − baseline_base)")
        if b_base is not None and pc_base is not None:
            out.append(f"- **Phase C 0-shot transfer (★ curriculum effect)**: {pc_base-b_base:+.3f}  (phase_c__base − baseline_base)")
        out.append("")

    if math:
        out += [f"## MATH500 (n={math.get('n','?')}, source: `{name_math}`)",
                ""]
        conds = ["baseline"] + sorted({k.split("__")[0] for k in math["results"] if k.startswith("phase_")})
        out += [to_table(math["results"], conds), ""]

    out += ["## All evaluation snapshots",
            "",
            "| dir | n | conditions |",
            "|---|---|---|"]
    for k, v in sorted(sums.items()):
        out.append(f"| `{k}` | {v.get('n','?')} | {len(v.get('results',{}))} |")
    out.append("")

    out_path = HERE / "ANALYSIS.md"
    out_path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {out_path} ({len(out)} lines)")


if __name__ == "__main__":
    main()
